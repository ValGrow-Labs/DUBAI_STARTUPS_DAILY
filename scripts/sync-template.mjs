import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderRouteHtml, getLocalArticleBySlug, getLocalArticlesForSitemap } from "../server/seo.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distHtmlPath = path.join(root, "dist", "index.html");
const templateOutPath = path.join(root, "api", "_template.js");

const builtHtml = fs.readFileSync(distHtmlPath, "utf8");

// Enrich static dist/index.html with homepage JSON-LD (Organization + WebSite) and deduplicated meta tags.
const { html: homeHtml } = renderRouteHtml(builtHtml, "/", {
  getArticle: getLocalArticleBySlug,
  getArticles: getLocalArticlesForSitemap,
});
fs.writeFileSync(distHtmlPath, homeHtml, "utf8");

// Bundle the raw Vite output template as an ESM module so Vercel serverless functions can import it reliably.
fs.writeFileSync(
  templateOutPath,
  `// Auto-generated by scripts/sync-template.mjs during vite build.\nexport const HTML_TEMPLATE = ${JSON.stringify(builtHtml)};\n`,
  "utf8"
);
console.log("[build-seo] Synced dist/index.html and api/_template.js");
